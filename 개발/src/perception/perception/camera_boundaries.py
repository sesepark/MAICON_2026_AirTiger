def camera_key(frame_id):
    """드론 사진의 frame_id → BUILT_IN 의 이름. "uav" → "main", "uav:test:test1" → "test1". 이름 그대로("test2" · "main")도 받는다. 모르면 None."""
    name = str(frame_id or "").strip()
    if not name:
        return None
    if name == "uav":
        return "main"
    if name.startswith("uav:test:"):
        name = name.split(":", 2)[2]
    return name if name in BUILT_IN else None


def built_in(camera):
    """그 카메라의 미리 맞춘 경계 → [dict] (없으면 빈 목록). camera 는 frame_id 나 이름."""
    entry = BUILT_IN.get(camera_key(camera) or "")
    return [dict(entry)] if isinstance(entry, dict) and entry.get("ok") and entry.get("hom") is not None else []
